    private sealed class PhraseNode
    {
        public readonly Dictionary<char,PhraseNode> Next=new();
        public string? Translation;
    }
    private static readonly PhraseNode Root=BuildPhrases();
    private static PhraseNode BuildPhrases()
    {
        var root=new PhraseNode();
        foreach(var phrase in Phrases)
        {
            var node=root;
            foreach(char letter in phrase.Key)
            {
                if(!node.Next.TryGetValue(letter,out var next))node.Next[letter]=next=new PhraseNode();
                node=next;
            }
            node.Translation=phrase.Value;
        }
        return root;
    }
    public static string Translate(string text,string language)
    {
        if(language!="uk"||text.Length==0)return text;
        // Longest whole phrase wins. A trie has bounded work per input position,
        // no first-use regex compilation or timeout on a busy loading frame, and
        // never translates words inside the replacement text for a second time.
        StringBuilder? result=null;
        int copied=0;
        for(int start=0;start<text.Length;start++)
        {
            if(start>0&&char.IsLetter(text,start-1))continue;
            var node=Root;
            string? translation=null;
            int matchEnd=start;
            for(int end=start;end<text.Length;end++)
            {
                if(!node.Next.TryGetValue(text[end],out var next))break;
                node=next;
                if(node.Translation is not null&&(end+1==text.Length||!char.IsLetter(text,end+1)))
                {
                    translation=node.Translation;
                    matchEnd=end+1;
                }
            }
            if(translation is null)continue;
            result??=new StringBuilder(text.Length);
            result.Append(text,copied,start-copied).Append(translation);
            copied=matchEnd;
            start=matchEnd-1;
        }
        return result is null?text:result.Append(text,copied,text.Length-copied).ToString();
    }
    public static string Normalize(string language)=>language.StartsWith("uk",StringComparison.OrdinalIgnoreCase)?"uk":language.StartsWith("ru",StringComparison.OrdinalIgnoreCase)?"ru":"en";
    public static string Cycle(string language,int delta){string[] codes=["en","ru","uk"];return codes[(Array.IndexOf(codes,Normalize(language))+Math.Sign(delta)+3)%3];}
