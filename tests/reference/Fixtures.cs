using var output=new StreamWriter(args[0]);
output.WriteLine("# Generated by unmodified PROMZONA 0.44.1 VehicleDynamics.cs; only data-holder adapter below.");
for(int kind=0;kind<=11;kind++)for(int scenario=0;scenario<5;scenario++) {
    double mass=kind is 11?18000:kind is 2 or 5?6000:1060;
    double vx=scenario==2?4:0,vz=scenario>1?20:0,angle=scenario==3?.4:0,w=scenario==3?.5:0;
    double throttle=scenario<2?1:scenario==4?-1:0,steering=scenario is 1 or 3?.6:0,traction=scenario==4?.6:1;
    bool brake=scenario==4,hand=scenario is 2 or 3;int steps=120;double dt=1.0/120;
    var c=new CityCar {Kind=kind,Mass=mass,Body=new Body2D{Vx=vx,Vy=vz,Angle=angle,W=w,HalfW=.9,HalfH=2.1,InvMass=1/mass,InvI=3/(mass*(.9*.9+2.1*2.1))}};
    for(int i=0;i<steps;i++)VehicleDynamics.Step(c,new(throttle,steering,brake,hand),dt,traction);
    output.WriteLine(string.Join(" ",new object[]{"vehicle",kind,mass,vx,vz,angle,w,throttle,steering,brake?1:0,hand?1:0,steps,dt,traction,c.Body.Vx,c.Body.Vy,c.Body.W,c.Steering}));
}
